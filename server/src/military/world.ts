/** Military helpers: geography, wars and sides, access rules, stat caches. Pure (no I/O beyond static data). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Division, DivisionTemplate, MilitaryState, NationMilitary, WorldState } from '../../../shared/types';
import { standardTemplates, terrainOf } from '../../../shared/military/catalog';
import { divisionStats, techMods, type DivisionStats, type Mods } from '../../../shared/military/stats';
import { PROVINCE_META } from '../state/provinces';
import { getRelation } from '../state/world';

const geoFile = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../data/province-geo.json');
/** Generated by scripts/build-province-geo.ts: areas and border-to-border distances (≤ 1,500 km). */
const GEO: { areas: Record<string, number>; near: Record<string, Record<string, number>>; sea: Record<string, Record<string, number>> } =
  JSON.parse(fs.readFileSync(geoFile, 'utf8'));
const AREAS = GEO.areas;

/** Relation at or above which a nation grants military access to another. */
export const ACCESS_RELATION = 50;
/** Max sea crossing (km, coast to coast) for a naval invasion. */
export const NAVAL_RANGE_KM = 600;

export const areaOf = (p: string) => AREAS[p] ?? 100_000;
/** Bigger provinces take more victories to occupy. 1 for anything under 40k km² (~4 for Ukraine, ~20 for Russia). */
export const sizeFactor = (p: string) => Math.max(1, Math.sqrt(areaOf(p) / 40_000));
export const neighbours = (p: string) => PROVINCE_META.get(p)?.neighbours ?? [];
export const isAdjacent = (a: string, b: string) => neighbours(a).includes(b);
export { terrainOf };

/** Shortest border-to-border distance in km (0 for the same or touching provinces, Infinity beyond 1,500 km). */
export function distanceKm(a: string, b: string): number {
  if (a === b) return 0;
  return GEO.near[a]?.[b] ?? Infinity;
}
/** Provinces reachable by a naval landing: not adjacent by land, coast to coast within range. */
export const seaNeighbours = (p: string) =>
  Object.entries(GEO.sea[p] ?? {}).filter(([q, d]) => d <= NAVAL_RANGE_KM && !isAdjacent(p, q)).map(([q]) => q);
export const canLand = (from: string, to: string) => !isAdjacent(from, to) && (GEO.sea[from]?.[to] ?? Infinity) <= NAVAL_RANGE_KM;

export function mil(state: WorldState): MilitaryState {
  if (!state.military) throw new Error('This scenario has no military layer');
  return state.military;
}

export function nationMil(state: WorldState, id: string): NationMilitary {
  const m = mil(state);
  return (m.nations[id] ??= {
    factories: 2, research: [null], completed: ['inf_digital', 'jet_gen4', 'doc_depth'], manpower: 50_000,
    stockpile: { small_arms: 300 }, production: [], templates: [], tankDesigns: [], jetDesigns: [],
  });
}

export const newId = (state: WorldState, prefix: string) => `${prefix}${mil(state).nextId++}`;

// ---- wars and sides --------------------------------------------------------

export function atWar(state: WorldState, a: string, b: string): boolean {
  if (a === b || !state.military) return false;
  return state.military.wars.some((w) => (w.a === a && w.b === b) || (w.a === b && w.b === a));
}

export function enemiesOf(state: WorldState, a: string): string[] {
  if (!state.military) return [];
  const out = new Set<string>();
  for (const w of state.military.wars) {
    if (w.a === a) out.add(w.b);
    if (w.b === a) out.add(w.a);
  }
  return [...out];
}

/** Same side: identical, or sharing a common enemy without being at war with each other. */
export function sameSide(state: WorldState, a: string, b: string): boolean {
  if (a === b) return true;
  if (atWar(state, a, b)) return false;
  const ea = new Set(enemiesOf(state, a));
  return enemiesOf(state, b).some((e) => ea.has(e));
}

/** Can `nation`'s divisions be in `province` (peacefully or by invading)? */
export function canEnter(state: WorldState, nation: string, province: string): 'friendly' | 'hostile' | false {
  const p = state.provinces[province];
  if (!p) return false;
  if (p.owner === nation || sameSide(state, nation, p.owner)) return 'friendly';
  if (atWar(state, nation, p.owner)) return 'hostile';
  // Occupied by us or our side?
  const occ = state.military?.occupation[province];
  if (occ && sameSide(state, nation, occ.by)) return 'friendly';
  if (getRelation(state, nation, p.owner) >= ACCESS_RELATION) return 'friendly';
  return false;
}

/** Does province contain divisions hostile to `nation`? */
export const hostileIn = (state: WorldState, nation: string, province: string) =>
  mil(state).divisions.some((d) => d.province === province && atWar(state, nation, d.owner));

/** A province is held by `nation`'s side if owned by it/its side, or it has our side's divisions and none hostile. */
export function friendlyGround(state: WorldState, nation: string, province: string): boolean {
  const p = state.provinces[province];
  if (!p) return false;
  if (hostileIn(state, nation, province)) return false;
  return canEnter(state, nation, province) === 'friendly';
}

// ---- templates and stats ---------------------------------------------------

const STD = standardTemplates();
export function findTemplate(nm: NationMilitary, id: string): DivisionTemplate | undefined {
  return nm.templates.find((t) => t.id === id) ?? STD.find((t) => t.id === id);
}

/** Per-call stat cache: stats depend on template + nation research, which don't change mid-phase. */
export class StatCache {
  private mods = new Map<string, Mods>();
  private stats = new Map<string, DivisionStats>();
  constructor(private state: WorldState) {}
  modsOf(nation: string): Mods {
    let m = this.mods.get(nation);
    if (!m) this.mods.set(nation, (m = techMods(nationMil(this.state, nation).completed)));
    return m;
  }
  div(d: Pick<Division, 'owner' | 'template'>): DivisionStats {
    const key = `${d.owner}|${d.template}`;
    let s = this.stats.get(key);
    if (!s) {
      const nm = nationMil(this.state, d.owner);
      const tpl = findTemplate(nm, d.template);
      s = tpl ? divisionStats(tpl, nm, this.modsOf(d.owner)) : FALLBACK;
      this.stats.set(key, s);
    }
    return s;
  }
}
const FALLBACK = divisionStats(STD[0], undefined);

/** Rough combat power, used by the AI and the UI to compare stacks. */
export function divisionPower(d: Division, st: DivisionStats): number {
  if (d.status !== 'ready') return 0;
  const orgFrac = st.org > 0 ? d.org / st.org : 1;
  return (st.soft + st.hard + st.breakthrough * 0.5 + st.defense * 0.3) * d.strength * (0.3 + orgFrac);
}

export function ordinal(n: number): string {
  const s = ['th', 'st', 'nd', 'rd'], v = n % 100;
  return n + (s[(v - 20) % 10] || s[v] || s[0]);
}

/** Moves divisions that are somewhere they may no longer be (after peace, transfers…) to their capital, or disbands them. */
export function cleanupPositions(state: WorldState): string[] {
  const m = mil(state);
  const notes: string[] = [];
  m.divisions = m.divisions.filter((d) => {
    const owner = state.nations[d.owner];
    if (!owner?.alive) return false;
    if (canEnter(state, d.owner, d.province)) return true;
    const home = state.provinces[owner.capital]?.owner === owner.id ? owner.capital : Object.values(state.provinces).find((p) => p.owner === owner.id)?.id;
    if (!home) return false;
    notes.push(`${d.name} (${owner.name}) withdrew to ${state.provinces[home].name}.`);
    d.province = home;
    d.order = null;
    d.entrench = 0;
    return true;
  });
  m.airWings = m.airWings.filter((w) => {
    const owner = state.nations[w.owner];
    if (!owner?.alive) return false;
    if (canEnter(state, w.owner, w.province) === 'friendly') return true;
    w.province = owner.capital;
    return true;
  });
  // Occupations by nations no longer at war with the owner are void.
  for (const [prov, occ] of Object.entries(m.occupation)) {
    const owner = state.provinces[prov]?.owner;
    if (!owner || !atWar(state, occ.by, owner)) delete m.occupation[prov];
  }
  return notes;
}

/** Static geography the client needs to give orders: land neighbours, sea links, terrain, area. */
export function geoForClient() {
  const out: Record<string, { n: string[]; sea: string[]; terrain: string; area: number }> = {};
  for (const id of Object.keys(AREAS)) out[id] = { n: neighbours(id), sea: seaNeighbours(id), terrain: terrainOf(id).id, area: AREAS[id] };
  return out;
}
