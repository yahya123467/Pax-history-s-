/**
 * Writes docs/PROMPTS.md with the exact system prompts the game uses, plus a
 * fully rendered example of each dynamic prompt for the Europe 1936 scenario.
 *
 *   npm run prompts
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DIPLOMACY_SUMMARY_SYSTEM_PROMPT,
  ENGINE_SYSTEM_PROMPT,
  HISTORY_SYSTEM_PROMPT,
  diplomacySummaryUserPrompt,
  diplomacySystemPrompt,
  engineUserPrompt,
  historyUserPrompt,
} from '../src/ai/prompts';
import { buildInitialState } from '../src/scenarios';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const state = buildInitialState('europe-1936', 'GER');
const block = (s: string) => '```text\n' + s + '\n```';

const md = `# Prompts

> Generated by \`npm run prompts\` from \`server/src/ai/prompts.ts\` — do not edit by hand.
> Examples are rendered for **Europe, 1936** with the player as **Germany**.

The game makes four kinds of AI call. Every JSON reply is shape-checked with zod
(retried up to 3 times with exponential backoff and a corrective message on failure),
then each state change is checked against the rules in \`server/src/validation/changes.ts\`.

## 1. Game engine — turn resolution

Sent on **End Turn**. Resolves the player's orders and generates 1–3 autonomous AI-nation events.

### System prompt
${block(ENGINE_SYSTEM_PROMPT)}

### User message (example)
${block(engineUserPrompt(state, 'Remilitarise the Rhineland and announce it as a defensive measure.'))}

## 2. Diplomacy — nation persona

Rebuilt for every chat message so it reflects the live world. The thread's last 20 messages follow it as user/assistant turns.

### System prompt (example: Italy talking to Germany)
${block(diplomacySystemPrompt(state, state.nations.ITA))}

## 3. Diplomacy — talks summary

Sent on **Conclude talks** (and automatically at End Turn for any open talks). Agreements go into the event log; the relation delta is clamped to ±15.

### System prompt
${block(DIPLOMACY_SUMMARY_SYSTEM_PROMPT)}

### User message (example)
${block(diplomacySummaryUserPrompt(state, state.nations.ITA, 'Germany (Adolf Hitler): ...\n\nItaly (Benito Mussolini): ...'))}

## 4. Memory — history compression

Sent when the event log passes 30 entries: everything but the newest 15 is folded into the "history so far" paragraph.

### System prompt
${block(HISTORY_SYSTEM_PROMPT)}

### User message (example)
${block(historyUserPrompt('', '- [1936-03] (world) Germany remilitarised the Rhineland.\n- [1936-04] (diplomacy) Talks between Germany and Italy ended without agreement.'))}
`;

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/PROMPTS.md'), md);
console.log('Wrote docs/PROMPTS.md');
